const STORAGE_KEY = 'dy:lang';

function getInitialLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'az' || saved === 'tr' || saved === 'ru') return saved;
    // Check navigator language
    if (typeof navigator !== 'undefined') {
      const nav = navigator.language?.toLowerCase() || '';
      if (nav.startsWith('az')) return 'az';
      if (nav.startsWith('ru')) return 'ru';
    }
  } catch {
    /* fallback to default */
  }
  return 'tr';
}

const initialLang = getInitialLang();
if (typeof document !== 'undefined') {
  document.documentElement.lang = initialLang;
  document.title = initialLang === 'ru' ? 'FastVideo · Короткие видео' : initialLang === 'az' ? 'FastVideo · Qısa Video' : 'FastVideo · Kısa Video';
}

const store = createStore<{ lang: Lang }>({ lang: initialLang });

export function getLang(): Lang {
  return store.get().lang;
}

export function setLang(lang: Lang) {
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    /* storage disabled */
  }
  store.set({ lang });
  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = lang === 'ru' ? 'FastVideo · Короткие видео' : lang === 'az' ? 'FastVideo · Qısa Video' : 'FastVideo · Kısa Video';
  }
}

export function t(key: TranslationKey, params?: Record<string, string | number>): string {
  const currentLang = store.get().lang;
  const dict = translations[currentLang] || translations.tr;
  let text: string = dict[key] || translations.tr[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function useI18n() {
  const state = useStore(store, (s) => s);

  const tFn = useCallback(
    (key: TranslationKey, params?: Record<string, string | number>) => {
      const dict = translations[state.lang] || translations.tr;
      let text: string = dict[key] || translations.tr[key] || key;
      if (params) {
        for (const [k, v] of Object.entries(params)) {
          text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
        }
      }
      return text;
    },
    [state.lang]
  );

  return useMemo(
    () => ({
      lang: state.lang,
      setLang,
      t: tFn
    }),
    [state.lang, tFn]
  );
}
